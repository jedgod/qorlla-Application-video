// Generates docs/API_CONTRACT.md from the route registrations in qorlla-portal/server (so the document cannot drift from the code).
// Usage: node cert/gen-api-contract.mjs [outfile]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = process.env.QORLLA_ROOT || path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'qorlla-portal', 'server');
const files = [];
(function walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (p.endsWith('.mjs')) files.push(p); } })(dir);

const ORIGIN = { 'workspace-tools.mjs': 'v4.4 notes / documents / QorllaMate', 'phone.mjs': 'v4.3 phone and receptionist', 'meeting-ai.mjs': 'v4.2 meeting intelligence', 'routes.mjs': 'v4.5 billing operations and platform admin', 'app.mjs': 'v4.0/4.1 core, billing and sales' };
const rows = [];
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
  for (const m of src.matchAll(/app\.(get|post|put|patch|delete)\(\s*(['"`/])((?:\\.|(?!\2)[^\\\n])*)\2?([^\n]*)/g)) {
    const method = m[1].toUpperCase(); let p = m[2] === '/' ? null : m[3];
    if (!p || !p.startsWith('/')) continue;
    const rest = m[4] || ''; const line = m[0];
    const auth = /adminOnly/.test(rest) ? 'platform admin' : /verified/.test(rest) ? 'provider signature' : /\bmember\b/.test(rest) ? (/billingRoles|roles\(/.test(rest) ? 'member + role' : 'member') : /\bidentity\b/.test(rest) ? 'signed-in user' : /METRICS|internal\/metrics/.test(p) ? 'bearer token' : 'public';
    rows.push({ method, path: p.replace(/\$\{A\}/g, '/api/v1/admin'), auth, area: ORIGIN[path.basename(f)] || path.basename(f), file: path.relative(root, f).replace(/\\/g, '/') });
  }
}
// template-literal admin routes use `${A}/...` — expand them
for (const f of files.filter((x) => x.endsWith('routes.mjs'))) {
  const src = fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
  for (const m of src.matchAll(/app\.(get|post|put|patch|delete)\(`\$\{A\}([^`]*)`,\s*([^\n]*)/g)) rows.push({ method: m[1].toUpperCase(), path: '/api/v1/admin' + m[2], auth: /adminOnly/.test(m[3]) ? 'platform admin' : 'public', area: ORIGIN['routes.mjs'], file: path.relative(root, f).replace(/\\/g, '/') });
}
const seen = new Set(); const out = rows.filter((r) => { const k = r.method + ' ' + r.path; if (seen.has(k)) return false; seen.add(k); return true; }).sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const groups = new Map(); for (const r of out) { if (!groups.has(r.area)) groups.set(r.area, []); groups.get(r.area).push(r); }
let md = '# Qorlla Workplace API contract (generated)\n\n> Generated by `node cert/gen-api-contract.mjs` from the route registrations in `qorlla-portal/server`. Do not edit by hand.\n>\n';
md += '> **Authentication classes** - `public`: no credentials (rate limited where noted). `provider signature`: authenticity is the telephony/payment provider\'s HMAC, never a cookie. `signed-in user`: valid MAIN-issued token (+ CSRF on unsafe methods). `member`: signed-in user who belongs to the selected workspace (taken from database membership). `member + role`: additionally an owner/admin/billing role. `platform admin`: id listed in `PLATFORM_ADMIN_USER_IDS`; everyone else receives 404. `bearer token`: `METRICS_TOKEN`, private network only.\n\n';
md += `Total routes: **${out.length}**.\n\n`;
for (const [area, list] of [...groups].sort()) {
  md += `## ${area}\n\n| Method | Path | Access |\n|---|---|---|\n` + list.map((r) => `| ${r.method} | \`${r.path}\` | ${r.auth} |`).join('\n') + '\n\n';
}
const target = process.argv[2] || path.join(root, 'docs', 'API_CONTRACT.md');
fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, md);
console.log(`wrote ${target} (${out.length} routes)`);
