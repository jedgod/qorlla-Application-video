'use strict';
// The sandbox regression check must fail when a package disables the sandbox (negative test) and pass for a clean package.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync, spawnSync } = require('node:child_process');
const { findProblems } = require('./linux-sandbox-check.cjs');
const CLI = path.join(__dirname, 'linux-sandbox-check.cjs');
const DESKTOP_OK = '[Desktop Entry]\nName=Qorlla\nExec=AppRun --enable-sandbox %U\nIcon=qorlla\nType=Application\n';

test('clean desktop entries and launchers pass', () => {
  assert.deepEqual(findProblems([{ path: 'a/qorlla.desktop', text: DESKTOP_OK }, { path: 'b/qorlla.desktop', text: '[Desktop Entry]\nExec=/opt/Qorlla/qorlla %U\n' }, { path: 'AppRun', text: '#!/bin/sh\nexec "$HERE/qorlla" "$@"\n' }]), []);
});
test('NEGATIVE: the exact line electron-builder generated by default is rejected', () => {
  const p = findProblems([{ path: 'squashfs-root/qorlla.desktop', text: DESKTOP_OK.replace('--enable-sandbox', '--no-sandbox') }]);
  assert.equal(p.length, 1); assert.match(p[0], /disables the Chromium sandbox/); assert.match(p[0], /qorlla\.desktop:3/);
});
test('NEGATIVE: every sandbox-disabling switch and environment variable is rejected, in a desktop entry or a launcher script', () => {
  for (const sw of ['--no-sandbox', '--disable-setuid-sandbox', '--disable-gpu-sandbox', '--disable-seccomp-filter-sandbox', '--NO-SANDBOX']) {
    assert.equal(findProblems([{ path: 'x.desktop', text: 'Exec=qorlla ' + sw + ' %U\n' }]).length, 1, sw);
    assert.equal(findProblems([{ path: 'AppRun', text: '#!/bin/sh\nexec ./qorlla ' + sw + ' "$@"\n' }]).length, 1, 'launcher ' + sw);
  }
  assert.equal(findProblems([{ path: 'AppRun', text: 'ELECTRON_DISABLE_SANDBOX=1 exec ./qorlla\n' }]).length, 1);
  assert.equal(findProblems([{ path: 'x.desktop', text: 'Exec=env ELECTRON_NO_SANDBOX=1 qorlla\n' }]).length, 1);
});
test('a mention in a comment or in a non-Exec desktop field is not a launch command', () => {
  assert.deepEqual(findProblems([{ path: 'x.desktop', text: '[Desktop Entry]\nComment=never use --no-sandbox\nExec=qorlla %U\n' }, { path: 'AppRun', text: '# do not pass --no-sandbox\nexec ./qorlla\n' }]), []);
});
test('end to end on real directories: the CLI exits 1 for a package that disables the sandbox, 0 for a clean one, 2 if it inspected nothing', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'sbx-'));
  try {
    const mk = (name, exec) => { const d = path.join(root, name, 'usr', 'share', 'applications'); fs.mkdirSync(d, { recursive: true }); fs.writeFileSync(path.join(d, 'qorlla.desktop'), DESKTOP_OK.replace(/Exec=.*/, 'Exec=' + exec)); return path.join(root, name); };
    const clean = mk('clean', '/opt/Qorlla/qorlla %U'), bad = mk('bad', 'AppRun --no-sandbox %U');
    assert.equal(spawnSync(process.execPath, [CLI, clean]).status, 0);
    const r = spawnSync(process.execPath, [CLI, clean, bad], { encoding: 'utf8' }); assert.equal(r.status, 1); assert.match(r.stdout, /SANDBOX CHECK FAILED/); assert.match(r.stdout, /--no-sandbox/);
    fs.mkdirSync(path.join(root, 'empty')); assert.equal(spawnSync(process.execPath, [CLI, path.join(root, 'empty')]).status, 2, 'passing without having inspected a desktop entry is refused');
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
});

test('NEGATIVE: a compiled AppRun with a baked-in --no-sandbox string is caught', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'sbx-')); try {
    fs.mkdirSync(path.join(root, 'sq')); fs.writeFileSync(path.join(root, 'sq', 'qorlla.desktop'), DESKTOP_OK);
    fs.writeFileSync(path.join(root, 'sq', 'AppRun'), Buffer.concat([Buffer.from([0x7f, 0x45, 0x4c, 0x46, 0, 0, 0]), Buffer.from('--no-sandbox'), Buffer.from([0, 0])]));
    const r = spawnSync(process.execPath, [CLI, path.join(root, 'sq')], { encoding: 'utf8' }); assert.equal(r.status, 1, r.stdout); assert.match(r.stdout, /AppRun/);
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
});
